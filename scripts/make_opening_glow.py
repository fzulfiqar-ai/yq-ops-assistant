"""
The opening's horizon glow, baked into CSS gradients (29-Oct-2026). Prints the block of market.css
between "/* glow: generated by scripts/make_opening_glow.py */" and "/* end glow */".

The opening's three glow arcs were full-screen ellipses drawn through filter: blur(31/21/51px), and the
compositor re-applies a filter on every frame the layer moves: through the dawn's rise and the exit
the opening stepped at 4-9 frames a second in software rendering (the owner's video) and stuttered on
a cold GPU. An image would fix that but not paint in the first frame (the boot frame's logo, measured
20-Sep-2026, does not reach the screen before the app mounts). A gradient is drawn with the first
paint, needs no file, and moves as a texture like any layer.

The three arcs sit in one .open-glow wrapper (round 2): they rise together as one layer.

How a gradient stands in for the blur: the glow is the arc's ::before, its own box grown by k all
round (inset -50% * k), so its closest-side ellipse is the arc's ellipse scaled by (1 + k) on both
axes. A blur turns the ellipse's edge into the Gaussian's erf profile, alpha = erfc(d / (sigma * sqrt 2)) / 2
at a distance d outside the edge; at the crest, the only part on screen, d is vertical, so a stop at
d sits at t = (1 + d / b) / (1 + k) of the gradient, b being the arc's half-height. b is the
reference screen's (landscape 1536x864, portrait 430x932, as .horizon.is-opening sizes the box), so
the glow scales with the screen like a picture of it would. k reaches 2.6 sigma past the edge.

    python scripts/make_opening_glow.py
"""
from __future__ import annotations

import math

# the glow's arcs (.open-glow > i:nth-child(1..3), once .horizon > i:nth-child(2..4)): colour token, blur radius (sigma) in px
ARCS = [(2, "--m-arc-3", 31), (3, "--m-arc-2", 21), (4, "--m-arc-1", 51)]
# reference screen and the share of its height that .horizon.is-opening > i takes (1 - top - bottom inset)
REFS = {"portrait": (932, 1 - 0.35 + 0.25), "landscape": (864, 1 - 0.23 + 0.50)}
STEPS = (-2, -1.25, -0.5, 0, 0.5, 1.25, 2, 2.6)  # d / sigma


def gradient(token: str, sigma: float, b: float) -> tuple[float, str]:
    k = 2.6 * sigma / b
    stops = [f"hsl(var({token}))"]
    for s in STEPS:
        t = (1 + s * sigma / b) / (1 + k) * 100
        a = 0.5 * math.erfc(s / math.sqrt(2))
        stops.append(("transparent" if s == STEPS[-1] else f"hsl(var({token}) / {a:.3f})") + f" {t:.2f}%")
    return k, "radial-gradient(closest-side, " + ", ".join(stops) + ")"


def main() -> None:
    out = ["/* glow: generated by scripts/make_opening_glow.py */"]
    for name, (h, share) in REFS.items():
        b = h * share / 2
        rules = []
        for n, token, sigma in ARCS:
            k, g = gradient(token, sigma, b)
            rules.append(f".horizon.is-opening > .open-glow > i:nth-child({n - 1})::before {{\n  --glow-k: {k:.4f};\n  background-image: {g};\n}}")
        block = "\n".join(rules)
        if name == "landscape":
            block = "@media (min-aspect-ratio: 1/1) {\n" + "\n".join("  " + line for line in block.splitlines()) + "\n}"
        out.append(block)
    out.append("/* end glow */")
    print("\n".join(out))


if __name__ == "__main__":
    main()
